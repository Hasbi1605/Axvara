// Offline R1 seed. Node >=22.18 uses native type stripping for the shared utility guard.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { isGamesNicknameProduct } from "../src/lib/games/sellable.ts";

const SOURCE = "ourastore.com riset 2026-11-09";
const CAPTURED = "2026-11-09T08:28:15Z";
const BRANDS = new Set(["free fire", "free fire max", "mobile legends", "pubg mobile"]);
const compare = (a, b) => a.buyer_sku_code < b.buyer_sku_code ? -1 : a.buyer_sku_code > b.buyer_sku_code ? 1 : 0;

function indexed(rows) {
  if (!Array.isArray(rows)) throw new Error("Expected a JSON array of SKU rows");
  const result = new Map();
  for (const row of rows) {
    if (!row || typeof row !== "object" || typeof row.buyer_sku_code !== "string"
      || !/^[a-zA-Z0-9_-]{1,80}$/.test(row.buyer_sku_code) || result.has(row.buyer_sku_code)) {
      throw new Error("Invalid or duplicate buyer_sku_code");
    }
    result.set(row.buyer_sku_code, row);
  }
  return result;
}

export function generateReferenceSeed(reference, skus) {
  const catalog = indexed(skus);
  const matches = indexed(reference?.matches);
  const selected = [];
  const discarded = [];
  for (const ref of [...matches.values()].sort(compare)) {
    const code = ref.buyer_sku_code;
    const sku = catalog.get(code);
    let reason;
    if (ref.match !== "exact") reason = "not_exact";
    else if (!sku) reason = "missing_sku";
    else if (code.endsWith("b") && catalog.has(code.slice(0, -1))) reason = "backup";
    else if (isGamesNicknameProduct(sku) || isGamesNicknameProduct({ buyer_sku_code: code, product_name: ref.our_name })) reason = "username_utility";
    else if (typeof sku.brand !== "string" || !BRANDS.has(sku.brand.trim().toLowerCase())) reason = "not_wave1";
    else if (!Number.isSafeInteger(ref.oura_price) || ref.oura_price <= 0) reason = "invalid_oura_price";
    else if (typeof sku.price !== "number" || !Number.isFinite(sku.price) || sku.price <= 0) reason = "invalid_cost";
    else if (ref.oura_price / sku.price < 0.5 || ref.oura_price / sku.price > 3) reason = "ratio_out_of_range";
    if (reason) discarded.push({ buyer_sku_code: code, reason });
    else selected.push({ buyer_sku_code: code, price: ref.oura_price, brand: sku.brand });
  }
  const values = selected.map(row => `('${row.buyer_sku_code}',${row.price},'${SOURCE}','${CAPTURED}','${CAPTURED}')`);
  const sql = "-- Generated by scripts/generate-games-reference-seed.mjs; do not edit.\n"
    + "-- Exact wave-1 primary SKU matches only; existing admin references are preserved.\n"
    + (values.length ? "INSERT INTO games_reference_prices(buyer_sku_code,price,source,captured_at,updated_at) VALUES\n"
      + values.join(",\n") + "\nON CONFLICT(buyer_sku_code) DO NOTHING;\n" : "-- No eligible reference prices.\n");
  return { sql, selected, discarded };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.length !== 4) throw new Error("Usage: node scripts/generate-games-reference-seed.mjs <reference.json> <skus.json>");
    const { sql, selected, discarded } = generateReferenceSeed(JSON.parse(readFileSync(process.argv[2], "utf8")), JSON.parse(readFileSync(process.argv[3], "utf8")));
    writeFileSync(new URL("../drizzle/migrations/0111_games_reference_seed.sql", import.meta.url), sql);
    const count = (rows, key) => Object.fromEntries([...new Set(rows.map(row => row[key]))].sort().map(value => [value, rows.filter(row => row[key] === value).length]));
    console.log(JSON.stringify({ selected: selected.length, by_brand: count(selected, "brand"), discarded_count: discarded.length,
      discarded_by_reason: count(discarded, "reason"), discarded }, null, 2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : "Seed generation failed");
    process.exitCode = 1;
  }
}
