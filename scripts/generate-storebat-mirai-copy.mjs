#!/usr/bin/env node
/**
 * Generate typed StoreBat and Mirai curated copy modules and the 0141
 * supplier_links migration from T6-copy.json.
 *
 * Usage:
 *   node scripts/generate-storebat-mirai-copy.mjs [path/to/T6-copy.json]
 */
import fs from "node:fs";
import path from "node:path";

const DEFAULT_INPUT =
  "/Users/macbookair/.paseo/orchestration/3545947e-72ed-4403-a2a2-489657b1974e/T6-copy.json";

const inputPath = process.argv[2] ?? DEFAULT_INPUT;
const raw = JSON.parse(fs.readFileSync(inputPath, "utf8"));

const FORBIDDEN_RE = /\b(?:storebat|ventebot)\b/i;

function assertCleanText(ctx, value) {
  if (typeof value !== "string" || !value.trim()) {
    throw new Error(`Missing or empty string at ${ctx}`);
  }
  if (FORBIDDEN_RE.test(value)) {
    throw new Error(`Forbidden supplier name in buyer copy at ${ctx}`);
  }
}

function sanitizeSupplierMap(sectionName, entries) {
  const out = {};
  for (const [familyKey, family] of Object.entries(entries)) {
    if (!Number.isInteger(family.category_id) || family.category_id <= 0) {
      throw new Error(`Invalid category_id for ${sectionName}.${familyKey}`);
    }
    assertCleanText(`${sectionName}.${familyKey}.description`, family.description);
    assertCleanText(`${sectionName}.${familyKey}.description_en`, family.description_en);

    const variants = {};
    for (const [sku, variant] of Object.entries(family.variants ?? {})) {
      const ctx = `${sectionName}.${familyKey}.variants.${sku}`;
      assertCleanText(`${ctx}.admin_terms`, variant.admin_terms);
      assertCleanText(`${ctx}.admin_terms_en`, variant.admin_terms_en);
      assertCleanText(`${ctx}.admin_activation`, variant.admin_activation);
      assertCleanText(`${ctx}.admin_activation_en`, variant.admin_activation_en);
      // Intentionally omit label, name, and notes (PM-only).
      variants[sku] = {
        admin_terms: variant.admin_terms,
        admin_terms_en: variant.admin_terms_en,
        admin_activation: variant.admin_activation,
        admin_activation_en: variant.admin_activation_en,
      };
    }

    out[familyKey] = {
      category_id: family.category_id,
      description: family.description,
      description_en: family.description_en,
      variants,
    };
  }
  return out;
}

function renderCopyModule(exportName, data) {
  return `// Auto-generated by scripts/generate-storebat-mirai-copy.mjs from T6-copy.json.
// Do not edit by hand; re-run the generator to update.

export type CuratedVariantCopyFields = {
  admin_terms: string;
  admin_terms_en: string;
  admin_activation: string;
  admin_activation_en: string;
};

export type CuratedFamilyCopy = {
  category_id: number;
  description: string;
  description_en: string;
  variants: Record<string, CuratedVariantCopyFields>;
};

export const ${exportName}: Record<string, CuratedFamilyCopy> = ${JSON.stringify(data, null, 2)};
`;
}

function collectExistingMigrationSlugs(migrationsDir) {
  const existing = new Set();
  for (const file of fs.readdirSync(migrationsDir).sort()) {
    if (!file.endsWith(".sql") || file.startsWith("0141_")) continue;
    const sql = fs.readFileSync(path.join(migrationsDir, file), "utf8");
    if (!sql.includes("supplier_links")) continue;
    for (const m of sql.matchAll(/\(\s*'([a-z0-9-]+)'\s*,\s*'/g)) {
      existing.add(m[1]);
    }
  }
  return existing;
}

const sqlQuote = (s) => `'${String(s).replace(/'/g, "''")}'`;

const storebatCopy = sanitizeSupplierMap("storebat", raw.storebat ?? {});
const miraiCopy = sanitizeSupplierMap("mirai", raw.mirai ?? {});

fs.writeFileSync("src/lib/storebat/copy.ts", renderCopyModule("STOREBAT_COPY", storebatCopy));
fs.writeFileSync("src/lib/mirai/copy.ts", renderCopyModule("MIRAI_COPY", miraiCopy));

const existingSlugs = collectExistingMigrationSlugs("drizzle/migrations");
const newLinks = (raw.links ?? []).filter((link) => !existingSlugs.has(link.slug));

const valuesSql = newLinks
  .map((l) => `  (${sqlQuote(l.slug)}, ${sqlQuote(l.destination)}, ${sqlQuote(l.title)})`)
  .join(",\n");

const migrationSql = `-- 0141_storebat_mirai_supplier_links.sql — Seed shortlink internal axvara.tech/go/:slug
-- untuk salinan produk & varian StoreBat dan MiraiAPI (generated from T6-copy.json).
-- INSERT OR IGNORE: idempoten, aman dijalankan ulang bila slug sudah ada via admin.
INSERT OR IGNORE INTO supplier_links (slug, destination, title) VALUES
${valuesSql};
`;

fs.writeFileSync("drizzle/migrations/0141_storebat_mirai_supplier_links.sql", migrationSql);

console.log(
  `Generated storebat (${Object.keys(storebatCopy).length} families), mirai (${Object.keys(miraiCopy).length} groups), 0141 (${newLinks.length} links).`,
);
