function customEmojiOn(): boolean {
  const flag = String(process.env.TELEGRAM_CUSTOM_EMOJI ?? "").trim().toLowerCase();
  return !(flag === "off" || flag === "false" || flag === "0");
}

/** ISO-2 → bendera Unicode (ID → 🇮🇩); selain dua huruf → null. */
export function flagChar(code: string | null | undefined): string | null {
  const c = String(code ?? "").trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(c)) return null;
  return String.fromCodePoint(...[...c].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}

/** Region tanpa ISO-2 (label supplier) → kode bendera atau globe. */
function regionKey(code: string | null | undefined, label?: string | null): string | null {
  const c = String(code ?? "").trim().toUpperCase();
  if (/^[A-Z]{2}$/.test(c)) return c;
  const l = String(label ?? "").trim().toLowerCase();
  if (c === "GLOBAL" || /^(global|international|internasional|latin america|amerika latin|latam|asia|sea|middle east|timur tengah)$/.test(l)) return "GLOBE";
  if (/^(europe|eropa|eu)$/.test(l)) return "EU";
  return null;
}

/** Ikon tombol region: bendera animasi, globe untuk region gabungan; {} bila bukan region. */
export function regionIcon(code: string | null | undefined, label?: string | null): { icon_custom_emoji_id?: string } {
  if (!customEmojiOn()) return {};
  const key = regionKey(code, label);
  const id = key === "GLOBE" ? CUSTOM_EMOJI_MAP["🌏"] : key ? FLAG_EMOJI[key] : undefined;
  return id ? { icon_custom_emoji_id: id } : {};
}

/** Bendera caption: animasi bila ada, fallback Unicode/globe; null bila bukan region. */
export function regionFlagHtml(code: string | null | undefined, label?: string | null): string | null {
  const key = regionKey(code, label);
  if (!key) return null;
  const fallback = key === "GLOBE" ? "🌏" : flagChar(key);
  if (!fallback) return null;
  const id = key === "GLOBE" ? CUSTOM_EMOJI_MAP["🌏"] : FLAG_EMOJI[key];
  return customEmojiOn() && id ? `<tg-emoji emoji-id="${id}">${fallback}</tg-emoji>` : fallback;
}
