// src/lib/telegram/send-document.ts — multipart sendDocument (text file)
// W-B owns this file: api.ts (W-A) keeps the JSON callApi path untouched.
// Telegram Bot API expects multipart/form-data for document uploads; the
// request body is a Blob so Workers/Edge `fetch` sets the boundary itself.
// Credential content MUST never be logged here.

import type { TelegramApiResponse, TelegramMessage, AnyReplyMarkup } from "@/lib/telegram/types";

const TELEGRAM_API_BASE = "https://api.telegram.org";
const SEND_DOCUMENT_TIMEOUT_MS = 25_000;

export type SendDocumentParams = {
  chat_id: number | string;
  /** Raw text content; sent as an in-memory UTF-8 file (no disk, no R2). */
  content: string;
  filename: string;
  caption?: string;
  parse_mode?: "HTML" | "Markdown" | "MarkdownV2";
  reply_markup?: AnyReplyMarkup;
};

function getToken(): string {
  const token = process.env.TELEGRAM_BOT_TOKEN;
  if (!token) throw new Error("TELEGRAM_BOT_TOKEN not configured");
  return token;
}

export async function sendDocument(params: SendDocumentParams): Promise<TelegramApiResponse<TelegramMessage>> {
  let token: string;
  try {
    token = getToken();
  } catch (error) {
    return { ok: false, description: error instanceof Error ? error.message : "token_missing" };
  }
  const url = `${TELEGRAM_API_BASE}/bot${token}/sendDocument`;

  // Filename is generated by the caller from an order code (ASCII), but guard
  // anyway so a stray quote/newline cannot break the Content-Disposition.
  const filename = String(params.filename || "credentials.txt").replace(/[^A-Za-z0-9._-]/g, "").slice(0, 96) || "credentials.txt";

  const form = new FormData();
  form.set("chat_id", String(params.chat_id));
  if (params.caption) form.set("caption", params.caption);
  if (params.parse_mode) form.set("parse_mode", params.parse_mode);
  if (params.reply_markup) form.set("reply_markup", JSON.stringify(params.reply_markup));
  form.set("document", new Blob([params.content], { type: "text/plain;charset=utf-8" }), filename);

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), SEND_DOCUMENT_TIMEOUT_MS);
  try {
    // Do NOT set Content-Type: fetch must add the multipart boundary.
    const res = await fetch(url, { method: "POST", body: form, signal: controller.signal });
    return (await res.json()) as TelegramApiResponse<TelegramMessage>;
  } catch (error) {
    if (error instanceof DOMException && error.name === "AbortError") {
      return { ok: false, description: "Request timeout" };
    }
    return { ok: false, description: error instanceof Error ? error.message : "Unknown error" };
  } finally {
    clearTimeout(timer);
  }
}
