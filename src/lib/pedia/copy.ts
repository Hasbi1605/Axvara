const SENTENCE_EN: [RegExp, string | ((...parts: string[]) => string)][] = [
  [/^Jumlah per pesanan (.+)\.$/, "Quantity per order $1."],
  [/^No Refill: jumlah yang drop tidak diisi ulang\.$/, "No Refill: dropped quantity is not topped up."],
  [/^Belum ada label drop; anggap drop bisa terjadi\.$/, "No drop label yet; assume some drop can happen."],
  [/^Target harus publik\. Jangan mengganti link, membuat target privat, atau menghapus target selama proses\.$/, "The target must be public. Don't change the link, make the target private, or delete it during processing."],
  [/^Tunggu pesanan sebelumnya untuk target yang sama selesai sebelum memesan kembali\.$/, "Wait for the previous order on the same target to finish before ordering again."],
  [/^Start time dan speed dapat berubah mengikuti antrean\.$/, "Start time and speed can change with the queue."],
  [/^Isi komentar kamu tulis sendiri\.$/, "You write the comments yourself."],
  [/^Status pesanan dapat dipantau di halaman pesanan\.$/, "You can follow the order status on the order page."],
  [/^Layanan ini menerima komentar acak dari akun (.+)\.$/, (accounts: string) => `This service accepts random comments from ${accounts} accounts.`],
];

function translateSentence(line: string, locale: Locale): string {
  if (locale !== "en" || !line) return line;
  for (const [re, to] of SENTENCE_EN) {
    const match = re.exec(line);
    if (!match) continue;
    return typeof to === "string" ? line.replace(re, to) : to(...match.slice(1));
  }
  // Refill promise: "Refill N hari [sejak pesanan dibuat|selesai], selama layanan masih tersedia."
  const refill = /^Refill (\d+) hari( sejak pesanan (?:dibuat|selesai))?, selama layanan masih tersedia\.$/.exec(line);
  if (refill) {
    const anchor = refill[2] ? (refill[2].includes("selesai") ? " since the order was completed" : " since the order was created") : "";
    return `Refill ${refill[1]} days${anchor}, while the service is still available.`;
  }
  const lifetime = /^Refill selama layanan masih tersedia\.$/.exec(line);
  if (lifetime) return "Refill while the service is still available.";
  const noRefill = /^No Refill: jumlah yang drop tidak diisi ulang\.$/.exec(line);
  if (noRefill) return "No Refill: dropped quantity is not topped up.";
  // Deskripsi hasil generator 0093: "<Metrik> <Platform> [Indonesia|global] dari akun <kualitas>."
  const desc = /^([A-Za-z ]+?) ([A-Za-z]+) (Indonesia|global) dari akun (.+?)\.$/.exec(line);
  if (desc) {
    const [, metric, platform, region, accounts] = desc;
    return `${platform} ${metric.toLowerCase()} ${region === "Indonesia" ? "Indonesia" : "worldwide"} from ${accountPhrase(accounts)}.`;
  }
  return line;
}

function accountPhrase(accounts: string): string {
  const raw = accounts.trim();
  const posts = /\s*berpostingan$/i.test(raw);
  const base = raw.replace(/\s*berpostingan$/i, "");
  const map: Record<string, string> = {
    "HQ": "HQ accounts", "Real": "Real accounts", "Real Look": "Real Look accounts",
    "Real People": "Real People accounts", "Real Human": "Real Human accounts",
    "lama": "old accounts", "campuran": "mixed accounts",
    "Indonesia campuran": "mixed Indonesian accounts", "Indonesia Real Human": "Indonesian Real Human accounts",
    "Indonesia Real": "Indonesian Real accounts", "Indonesia Real Look": "Indonesian Real Look accounts",
    "Indonesia HQ": "Indonesian HQ accounts", "Indonesia": "Indonesian accounts",
  };
  const phrase = map[base] ?? (base ? `${base} accounts` : "accounts");
  return posts ? phrase.replace(/ accounts$/, " accounts with posts") : phrase;
}

