/** Teks bebas layanan (deskripsi, syarat, instruksi) baris per baris dengan fallback ID. */
export function pediaServiceText(text: string | null | undefined, locale: Locale): string {
  if (!text || locale !== "en") return text ?? "";
  return text.split("\n").map((line) => {
    const trimmed = line.trim();
    if (!trimmed) return line;
    // Instruksi bernomor: "1. Buka target ..." → terjemahkan isi kalimatnya.
    const numbered = /^(\d+\.)\s+(.*)$/.exec(trimmed);
    const out = numbered ? `${numbered[1]} ${translateSentence(numbered[2], locale)}` : translateSentence(trimmed, locale);
    // Pemisah ribuan Indonesia → EN, kecuali baris berisi URL (jangan ubah angka di dalam link).
    return /https?:\/\//i.test(out) ? out : thousands(out);
  }).join("\n");
}
