/** Angka gaya pembeli: pemisah ribuan mengikuti locale, bukan tebakan. */
export const pediaNumber = (value: number, locale: Locale): string =>
  value.toLocaleString(locale === "en" ? "en-US" : "id-ID");

/** Isi template "{name}" tanpa mengubah teks lain. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in vars ? String(vars[key]) : whole));
}

